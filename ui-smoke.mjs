import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
fs.mkdirSync('.preview',{recursive:true});
const browser = await chromium.launch({headless:true,...(process.env.PW_CHANNEL?{channel:process.env.PW_CHANNEL}:{})});
const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
await context.route('**/api/action/**',r=>r.abort());
const page = await context.newPage();
page.setDefaultTimeout(15000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.DASHBOARD_URL||'http://192.168.0.2/',{waitUntil:'domcontentloaded'});
await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
await page.locator('.storage-card .chart').first().waitFor();
// Flat zero-rate paths have zero-height SVG bounds and are still valid charts.
await page.locator('.storage-card .chart path').first().waitFor({state:'attached'});
assert.ok((await page.locator('.storage-card .chart path').first().getAttribute('d'))?.startsWith('M'));
await page.screenshot({path:'.preview/desktop.png',fullPage:true});
await page.getByRole('button',{name:'Storage',exact:true}).click();
for(const range of ['15m','1h','6h','24h']){
 const response=page.waitForResponse(r=>r.url().includes('/api/storage?window=')&&r.ok());
 await page.getByRole('button',{name:range,exact:true}).click();await response;
 assert.equal(await page.locator('.storage-card').count(),4);
 assert.ok(await page.locator('.storage-card').first().locator('.chart path').count()>0);
}
await page.getByRole('button',{name:'Capacity used',exact:true}).click();
await page.getByText('Parity has no filesystem capacity to chart.').waitFor();
await page.screenshot({path:'.preview/storage.png',fullPage:true});
await page.getByRole('button',{name:'All services 27',exact:true}).click();
await page.getByRole('textbox',{name:'Filter services',exact:true}).fill('does-not-exist');
await page.getByRole('heading',{name:'No matching services'}).waitFor();
await page.getByRole('button',{name:'Clear filters',exact:true}).click();
await page.getByRole('button',{name:'Pin Scrutiny',exact:true}).click();
await page.reload();
await page.getByRole('button',{name:'Unpin Scrutiny',exact:true}).waitFor();
await page.getByRole('button',{name:'Unpin Scrutiny',exact:true}).click();
await page.keyboard.press('Control+k');
await page.getByRole('textbox',{name:'Search service names and IPs'}).fill('sab');
assert.equal(await page.locator('.command-results a').count(),1);
assert.equal(await page.locator('.command-results a').getAttribute('href'),'http://192.168.0.13:8085');
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('dialog').count(),0);
await page.getByRole('button',{name:'Network & DNS',exact:true}).click();
await page.getByRole('button',{name:'Pause blocking · 5 min',exact:true}).click();
await page.getByRole('dialog').waitFor();
await page.getByRole('button',{name:'Cancel',exact:true}).click();
assert.equal(await page.getByRole('dialog').count(),0);
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Open navigation',exact:true}).click();
await page.getByRole('button',{name:'Storage',exact:true}).click();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'.preview/mobile.png',fullPage:true});
await page.getByRole('button',{name:'Find a service',exact:true}).click();
await page.getByRole('textbox',{name:'Search service names and IPs'}).fill('pve');
await page.keyboard.press('Escape');
assert.deepEqual(errors,[]);
console.log('PASS: desktop/mobile, all history ranges, charts, capacity, search, favorites persistence, dialog cancel, no page errors or mobile overflow.');
await browser.close();
