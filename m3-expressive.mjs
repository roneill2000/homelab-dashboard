// CSS has no spring timing function, so each spring is simulated (unit mass, x 0 -> 1, released at rest) and written
// as a linear() easing over the time it takes to settle within 0.1% of the target.
import { writeFileSync } from 'node:fs';

const SPRINGS = {
  // name: [stiffness, damping ratio]
  'expressive-fast-spatial': [800, 0.6], 'expressive-default-spatial': [380, 0.8], 'expressive-slow-spatial': [200, 0.8],
  'standard-fast-spatial': [1400, 0.9], 'standard-default-spatial': [700, 0.9], 'standard-slow-spatial': [300, 0.9],
  'fast-effects': [3800, 1], 'default-effects': [1600, 1], 'slow-effects': [800, 1],
};

function spring(k, z) {
  const w = Math.sqrt(k), dt = 1 / 2000; let x = 0, v = 0, t = 0; const pts = [[0, 0]];
  // integrate until settled (|1-x| < 0.001 and |v| small) for 0.3 s straight, or 3 s max
  let calm = 0;
  while (t < 3) {
    const a = -k * (x - 1) - 2 * z * w * v; v += a * dt; x += v * dt; t += dt;
    pts.push([t, x]);
    if (Math.abs(1 - x) < 0.001 && Math.abs(v) < 0.05) { calm += dt; if (calm > 0.05) break; } else calm = 0;
  }
  const T = t, step = Math.max(1, Math.floor(pts.length / 60));
  const sampled = pts.filter((_, i) => i % step === 0); sampled.push([T, 1]);
  const easing = 'linear(' + sampled.map(([ti, xi]) => `${+xi.toFixed(4)} ${+(ti / T * 100).toFixed(2)}%`).join(',') + ')';
  return { ms: Math.round(T * 1000), easing };
}

